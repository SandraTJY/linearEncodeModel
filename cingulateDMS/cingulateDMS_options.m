    % *LEMGrin_options*: Sets all options for the analysis of neuromodulators (DA/ ACh)
    % from the instrumental task in the vidDeconv (video deconvolution) study.
    % 
    % OUT:
    % options - the struct that holds all analysis options

%%%% --- General Set-Up ---
addpath(genpath('../utils'));
addpath(genpath('../external'));
addpath(genpath('../main'));
addpath(genpath('../data'));
addpath(genpath('../exampleData'));
addpath(genpath('../examples'));

%%% --- ENTER YOUR PATHS HERE ---
% Get the current directory and add all subfolders
addpath(genpath(pwd)); % You should be at the root of your code directory

% Set data root paths relative to the current directory
options.bhvDataRoot    = '//qnap-al001.dpag.ox.ac.uk/STan/Data/cingulateDMS_output/analysis/';
options.neuralDataRoot = '//qnap-al001.dpag.ox.ac.uk/STan/Data/cingulateDMS_output/analysis/';
options.rawDataRoot    = '//qnap-al001.dpag.ox.ac.uk/Data/';
options.vidDataRoot    = '/Volumes/Data'; % macOS config

% Data file name definition
options.bhvFileExtension = '_CorrectedeventTimes_withLicks.csv'; % please change
